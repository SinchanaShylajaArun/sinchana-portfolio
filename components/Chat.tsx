"use client";
// The chat box on the Ask page. Runs in the browser: it keeps the conversation
// in state, sends each question to /api/ask, and shows the answer as it streams in.

import { useEffect, useRef, useState } from "react";
import type { Source } from "@/lib/rag/answer";

type Message = { role: "user" | "assistant"; content: string; sources?: Source[] };

const WELCOME: Message = {
  role: "assistant",
  content: "Hi! Ask me about Sinchana's projects, experience, or skills.",
};

const SUGGESTIONS = [
  "Where has she interned?",
  "What computer vision work has she done?",
  "Which hackathons has she won?",
  "What does she teach?",
];

export default function Chat() {
  const [messages, setMessages] = useState<Message[]>([WELCOME]);
  const [input, setInput] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const logRef = useRef<HTMLDivElement>(null);

  // Keep the newest message in view.
  useEffect(() => {
    logRef.current?.scrollTo({ top: logRef.current.scrollHeight, behavior: "smooth" });
  }, [messages]);

  // Replace the last message (the answer being streamed) with new content.
  const updateLast = (patch: Partial<Message>) =>
    setMessages((m) => [...m.slice(0, -1), { ...m[m.length - 1], ...patch }]);

  async function ask(text: string) {
    const question = text.trim();
    if (!question) {
      setError("Type a question first.");
      return;
    }
    if (busy) return;
    setError("");
    setInput("");
    setBusy(true);

    // Everything except the welcome message goes to the server as history.
    const history = messages.slice(1).map(({ role, content }) => ({ role, content }));
    setMessages((m) => [...m, { role: "user", content: question }, { role: "assistant", content: "" }]);

    try {
      const res = await fetch("/api/ask", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ question, history }),
      });
      if (!res.ok || !res.body) {
        updateLast({ content: (await res.text()) || "Something went wrong. Please try again." });
        return;
      }

      let sources: Source[] = [];
      try {
        sources = JSON.parse(decodeURIComponent(res.headers.get("X-Sources") ?? "[]"));
      } catch {}

      // Read the streamed answer chunk by chunk and show it as it arrives.
      const reader = res.body.getReader();
      const decoder = new TextDecoder();
      let answer = "";
      for (;;) {
        const { value, done } = await reader.read();
        if (done) break;
        answer += decoder.decode(value, { stream: true });
        updateLast({ content: answer });
      }

      // Show only the sources the answer actually cited, e.g. [1] and [3].
      const cited = new Set([...answer.matchAll(/\[(\d+)\]/g)].map((m) => Number(m[1])));
      updateLast({ content: answer, sources: sources.filter((s) => cited.has(s.n)) });
    } catch {
      updateLast({ content: "I couldn't reach the server. Check your connection and try again." });
    } finally {
      setBusy(false);
    }
  }

  return (
    <>
      <div className="chat">
        <div className="chat-head">Assistant</div>
        <div className="chat-log" ref={logRef} aria-live="polite">
          {messages.map((m, i) => (
            <div key={i} className={`bubble ${m.role === "user" ? "me" : "ai"}`}>
              {m.content || <span className="thinking">Thinking…</span>}
              {m.sources && m.sources.length > 0 && (
                <div className="sources">
                  {m.sources.map((s) => (
                    <a key={s.n} href={s.href}>[{s.n}] {s.title}</a>
                  ))}
                </div>
              )}
            </div>
          ))}
        </div>

        {messages.length === 1 && (
          <div className="suggestions">
            {SUGGESTIONS.map((s) => (
              <button type="button" className="suggestion" key={s} onClick={() => ask(s)}>{s}</button>
            ))}
          </div>
        )}

        <form
          className="chat-form"
          onSubmit={(e) => {
            e.preventDefault();
            ask(input);
          }}
        >
          <input
            className="input"
            value={input}
            onChange={(e) => {
              setInput(e.target.value);
              setError("");
            }}
            placeholder="Ask about projects, skills, experience…"
            maxLength={500}
            aria-label="Your question"
            aria-invalid={!!error}
          />
          <button type="submit" className="btn" disabled={busy}>{busy ? "…" : "Ask"}</button>
        </form>
        {error && <p className="chat-error">{error}</p>}
      </div>
      <p className="fine">Answers are generated by AI from retrieved passages and may be imperfect.</p>
    </>
  );
}
